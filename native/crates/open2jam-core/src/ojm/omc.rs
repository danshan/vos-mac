/// Converts a structurally valid OMC bank into plain OJM in place.
/// On cancellation the caller must discard the partially transformed buffer.
/// Hash the original source before this operation; the result is derived data.
pub fn decode_omc_in_place(
    bytes: &mut [u8],
    checkpoint: &mut impl FnMut() -> Result<(), CoreError>,
) -> Result<(), CoreError> {
    // Validate every section before changing any payload or the signature.
    parse_bank(bytes, b"OMC\0", checkpoint)?;
    let ogg_start = u32_at(bytes, 12) as usize;
    let mut offset = 20;
    let mut key = 0xff_u8;
    let mut counter = 0_u32;
    while offset < ogg_start {
        checkpoint()?;
        let size = u32_at(bytes, offset + 52) as usize;
        offset += 56;
        let payload = &mut bytes[offset..offset + size];
        let mut encoded = Vec::with_capacity(size);
        for chunk in payload.chunks(65_536) {
            checkpoint()?;
            encoded.extend_from_slice(chunk);
        }
        let block_size = size / 17;
        let permutation = &REARRANGE[(size % 17) * 17..][..17];
        for (block, &destination) in permutation.iter().enumerate() {
            let source = &encoded[block * block_size..(block + 1) * block_size];
            let target = &mut payload[destination * block_size..(destination + 1) * block_size];
            for (input, output) in source.chunks(65_536).zip(target.chunks_mut(65_536)) {
                checkpoint()?;
                output.copy_from_slice(input);
            }
        }
        for chunk in payload.chunks_mut(65_536) {
            checkpoint()?;
            for byte in chunk {
                let original = *byte;
                if (u32::from(key) << counter) & 0x80 != 0 {
                    *byte = !original;
                }
                counter += 1;
                if counter == 8 {
                    counter = 0;
                    key = original;
                }
            }
        }
        offset += size;
    }
    checkpoint()?;
    bytes[..4].copy_from_slice(b"OJM\0");
    Ok(())
}
